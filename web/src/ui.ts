export type UIKey = keyof typeof DICT

const COL: Record<ContentLang, 0 | 1 | 2 | 3> = { zh: 0, en: 1, ko: 2, ja: 3 }

/** 非 React 环境用：按语言取 UI 文案，缺失回退简中。 */
export function uiText(lang: ContentLang, key: UIKey): string {
  const row = (DICT as Record<string, Row>)[key]
  if (!row) return key
  return row[COL[lang]] || row[0]
}

/** 组件内用：const t = useUI(); t('nav_home') */
export function useUI() {
  const { lang } = useLang()
  return (key: UIKey) => uiText(lang, key)
}

/** 占位符替换：t('x', { n: 3 }) → 文案里的 {n} 被替换 */
export function fmt(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m))
}
